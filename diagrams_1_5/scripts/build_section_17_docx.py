def rows_from_uploaded(idx):
    """Переносит строки данных таблицы idx из загруженного файла дословно."""
    up = Document(UP)
    tb = up.tables[idx]
    out = []
    for r in tb.rows[1:]:
        cells = [c.text.strip().replace("\n", " ") for c in r.cells]
        out.append(cells)
    return out


