FONT = "Times New Roman"
MONO = "Consolas"

doc = Document()
st = doc.styles["Normal"]
st.font.name = FONT; st.font.size = Pt(14)
st.element.rPr.rFonts.set(qn("w:eastAsia"), FONT)
st.paragraph_format.line_spacing = 1.5; st.paragraph_format.space_after = Pt(0)
sec = doc.sections[0]
sec.left_margin = Cm(3); sec.right_margin = Cm(1.5); sec.top_margin = Cm(2); sec.bottom_margin = Cm(2)
USABLE_CM = 16.5
fig_no = 0; tbl_no = 0; lst_no = 0


def _f(run, size=14, bold=False, italic=False, font=FONT):
    run.font.name = font; run.font.size = Pt(size); run.bold = bold; run.italic = italic
    run._element.rPr.rFonts.set(qn("w:eastAsia"), font)


def heading(text):
    p = doc.add_paragraph(); p.paragraph_format.space_before = Pt(12)
    p.paragraph_format.space_after = Pt(6); p.paragraph_format.keep_with_next = True
    _f(p.add_run(text), 14, bold=True); return p


def subpara(text):
    """Полужирный подзаголовок логической части (без номера)."""
    p = doc.add_paragraph(); p.paragraph_format.space_before = Pt(8)
    p.paragraph_format.space_after = Pt(2); p.paragraph_format.keep_with_next = True
    _f(p.add_run(text), 14, bold=True); return p


def body(text, first_indent=True):
    p = doc.add_paragraph(); p.alignment = WD_ALIGN_PARAGRAPH.JUSTIFY
    if first_indent:
        p.paragraph_format.first_line_indent = Cm(0.75)
    _f(p.add_run(text), 14); return p


def bullets(items):
    for it in items:
        p = doc.add_paragraph(); p.alignment = WD_ALIGN_PARAGRAPH.JUSTIFY
        p.paragraph_format.left_indent = Cm(0.75); p.paragraph_format.first_line_indent = Cm(-0.5)
        _f(p.add_run("– " + it), 14)


def figure(fname, caption, width_cm=USABLE_CM):
    global fig_no; fig_no += 1
    path = os.path.join(DIA, fname)
    w, h = Image.open(path).size
    disp_w = width_cm
    if (h / w) * width_cm > 21:   # очень высокая картинка — ограничиваем по высоте
        disp_w = 21 * w / h
    p = doc.add_paragraph(); p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    p.paragraph_format.space_before = Pt(6); p.paragraph_format.keep_together = True
    p.add_run().add_picture(path, width=Cm(disp_w))
    cap = doc.add_paragraph(); cap.alignment = WD_ALIGN_PARAGRAPH.CENTER
    cap.paragraph_format.space_after = Pt(10)
    _f(cap.add_run(f"Рисунок {fig_no} – {caption}"), 14)
    return fig_no


def _set_borders(p):
    pPr = p._p.get_or_add_pPr()
    pbdr = OxmlElement("w:pBdr")
    for edge in ("top", "left", "bottom", "right"):
        e = OxmlElement(f"w:{edge}")
        e.set(qn("w:val"), "single"); e.set(qn("w:sz"), "6")
        e.set(qn("w:space"), "6"); e.set(qn("w:color"), "808080")
        pbdr.append(e)
    pPr.append(pbdr)
    sh = OxmlElement("w:shd")
    sh.set(qn("w:val"), "clear"); sh.set(qn("w:color"), "auto"); sh.set(qn("w:fill"), "F5F5F5")
    pPr.append(sh)


def listing(lines, caption, size=8.5):
    global lst_no; lst_no += 1
    cap = doc.add_paragraph(); cap.alignment = WD_ALIGN_PARAGRAPH.LEFT
    cap.paragraph_format.space_before = Pt(6); cap.paragraph_format.space_after = Pt(2)
    cap.paragraph_format.keep_with_next = True
    _f(cap.add_run(f"Листинг {lst_no} – {caption}"), 13)
    p = doc.add_paragraph(); p.paragraph_format.line_spacing = 1.0
    p.paragraph_format.space_after = Pt(10); p.paragraph_format.keep_together = True
    _set_borders(p)
    for i, ln in enumerate(lines):
        run = p.add_run(("" if i == 0 else "\n") + ln)
        _f(run, size, font=MONO)
    return lst_no


def _shade(cell, hexc):
    tcPr = cell._tc.get_or_add_tcPr(); sh = OxmlElement("w:shd")
    sh.set(qn("w:val"), "clear"); sh.set(qn("w:color"), "auto"); sh.set(qn("w:fill"), hexc); tcPr.append(sh)


def _ct(cell, text, bold=False, size=12, align=None):
    cell.text = ""; p = cell.paragraphs[0]
    if align is not None: p.alignment = align
    p.paragraph_format.line_spacing = 1.0; p.paragraph_format.space_after = Pt(0)
    _f(p.add_run(text), size, bold=bold)


def table_caption(title):
    global tbl_no; tbl_no += 1
    p = doc.add_paragraph(); p.alignment = WD_ALIGN_PARAGRAPH.RIGHT; p.paragraph_format.space_before = Pt(8)
    _f(p.add_run(f"Таблица {tbl_no}"), 14)
    p2 = doc.add_paragraph(); p2.alignment = WD_ALIGN_PARAGRAPH.CENTER; p2.paragraph_format.space_after = Pt(2)
    _f(p2.add_run(title), 14); return tbl_no


def grid_table(headers, rows, widths=None):
    t = doc.add_table(rows=1 + len(rows), cols=len(headers)); t.style = "Table Grid"
    t.alignment = WD_TABLE_ALIGNMENT.CENTER
    for j, h in enumerate(headers):
        _ct(t.rows[0].cells[j], h, bold=True, align=WD_ALIGN_PARAGRAPH.LEFT); _shade(t.rows[0].cells[j], "D9D9D9")
    for i, row in enumerate(rows, start=1):
        for j, val in enumerate(row):
            _ct(t.rows[i].cells[j], val, align=WD_ALIGN_PARAGRAPH.LEFT)
    if widths:
        for i in range(len(rows) + 1):
            for j, wd in enumerate(widths):
                t.rows[i].cells[j].width = Cm(wd)
    doc.add_paragraph().paragraph_format.space_after = Pt(2)
    return t


