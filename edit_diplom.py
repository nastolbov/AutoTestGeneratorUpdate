def make_para(text, align='justify', first_line='0.75', bold=False, size_pt=14, before_space=False):
    """Создаёт w:p параграф с заданным форматированием."""
    p = OxmlElement('w:p')
    pPr = OxmlElement('w:pPr')

    # Spacing 1.5
    spacing = OxmlElement('w:spacing')
    spacing.set(qn('w:line'), '360')  # 1.5 line = 360 (1pt = 20)
    spacing.set(qn('w:lineRule'), 'auto')
    if before_space:
        spacing.set(qn('w:before'), '240')
    pPr.append(spacing)

    # Indentation
    if first_line:
        ind = OxmlElement('w:ind')
        ind.set(qn('w:firstLine'), str(int(float(first_line) * 567)))  # cm to twips: 1cm = 567 twips
        pPr.append(ind)

    # Alignment
    jc = OxmlElement('w:jc')
    jc.set(qn('w:val'), align)
    pPr.append(jc)

    p.append(pPr)

    # Run
    r = OxmlElement('w:r')
    rPr = OxmlElement('w:rPr')
    rFonts = OxmlElement('w:rFonts')
    rFonts.set(qn('w:ascii'), 'Times New Roman')
    rFonts.set(qn('w:hAnsi'), 'Times New Roman')
    rFonts.set(qn('w:cs'), 'Times New Roman')
    rPr.append(rFonts)
    sz = OxmlElement('w:sz')
    sz.set(qn('w:val'), str(size_pt * 2))
    rPr.append(sz)
    szCs = OxmlElement('w:szCs')
    szCs.set(qn('w:val'), str(size_pt * 2))
    rPr.append(szCs)
    if bold:
        b = OxmlElement('w:b')
        rPr.append(b)
    r.append(rPr)
    t = OxmlElement('w:t')
    t.set(qn('xml:space'), 'preserve')
    t.text = text
    r.append(t)
    p.append(r)
    return p


