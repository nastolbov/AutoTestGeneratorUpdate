def make_table(headers, rows, font_size=10):
    """Создаёт таблицу с заголовком и строками."""
    tbl = OxmlElement('w:tbl')
    # tblPr
    tblPr = OxmlElement('w:tblPr')
    tblW = OxmlElement('w:tblW')
    tblW.set(qn('w:w'), '5000')
    tblW.set(qn('w:type'), 'pct')
    tblPr.append(tblW)
    tblBorders = OxmlElement('w:tblBorders')
    for bord in ['top', 'left', 'bottom', 'right', 'insideH', 'insideV']:
        b = OxmlElement(f'w:{bord}')
        b.set(qn('w:val'), 'single')
        b.set(qn('w:sz'), '4')
        b.set(qn('w:color'), '000000')
        tblBorders.append(b)
    tblPr.append(tblBorders)
    tblLayout = OxmlElement('w:tblLayout')
    tblLayout.set(qn('w:type'), 'fixed')
    tblPr.append(tblLayout)
    tbl.append(tblPr)

    # tblGrid с пропорциями колонок
    n_cols = len(headers)
    tblGrid = OxmlElement('w:tblGrid')
    col_widths = {
        5: [1100, 2300, 1900, 1900, 2200],  # для табл. модулей
        4: [1100, 3200, 2300, 2800],
    }
    widths = col_widths.get(n_cols, [10000 // n_cols] * n_cols)
    for w in widths:
        gridCol = OxmlElement('w:gridCol')
        gridCol.set(qn('w:w'), str(w))
        tblGrid.append(gridCol)
    tbl.append(tblGrid)

    # Header row
    tr = OxmlElement('w:tr')
    trPr = OxmlElement('w:trPr')
    tblHeader = OxmlElement('w:tblHeader')  # повторять заголовок при переносе
    trPr.append(tblHeader)
    tr.append(trPr)
    for i, h in enumerate(headers):
        tc = OxmlElement('w:tc')
        tcPr = OxmlElement('w:tcPr')
        tcW = OxmlElement('w:tcW')
        tcW.set(qn('w:w'), str(widths[i]))
        tcW.set(qn('w:type'), 'dxa'); tcPr.append(tcW)
        vAlign = OxmlElement('w:vAlign'); vAlign.set(qn('w:val'), 'center'); tcPr.append(vAlign)
        tc.append(tcPr)
        # Внутренний параграф с центром, без отступа, жирный
        p = make_para(h, align='center', first_line=None, bold=True, size_pt=font_size)
        tc.append(p)
        tr.append(tc)
    tbl.append(tr)

    # Data rows
    for row in rows:
        tr = OxmlElement('w:tr')
        for i, cell_text in enumerate(row):
            tc = OxmlElement('w:tc')
            tcPr = OxmlElement('w:tcPr')
            tcW = OxmlElement('w:tcW')
            tcW.set(qn('w:w'), str(widths[i])); tcW.set(qn('w:type'), 'dxa'); tcPr.append(tcW)
            tc.append(tcPr)
            p = make_para(str(cell_text), align='left', first_line=None, size_pt=font_size)
            tc.append(p)
            tr.append(tc)
        tbl.append(tr)
    return tbl

