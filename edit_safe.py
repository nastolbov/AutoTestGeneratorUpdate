def add_p(text, bold=False, align=WD_ALIGN_PARAGRAPH.JUSTIFY, first_line_cm=0.75, size_pt=14):
    p = d2.add_paragraph()
    pf = p.paragraph_format
    pf.alignment = align
    pf.line_spacing = 1.5
    if first_line_cm:
        pf.first_line_indent = Cm(first_line_cm)
    r = p.add_run(text)
    r.font.name = 'Times New Roman'
    r.font.size = Pt(size_pt)
    r.font.bold = bold
    rPr = r._element.find(qn('w:rPr'))
    if rPr is not None:
        rFonts = rPr.find(qn('w:rFonts'))
        if rFonts is not None:
            rFonts.set(qn('w:cs'), 'Times New Roman')
    return p

def add_h(text):
    """Подзаголовок — bold, LEFT, 0.75."""
    return add_p(text, bold=True, align=WD_ALIGN_PARAGRAPH.LEFT)

def add_bul(text):
    return add_p(f'•\t{text}')

def add_tbl(headers, rows, font_size=10, col_widths_cm=None):
    tbl = d2.add_table(rows=len(rows) + 1, cols=len(headers))
    tbl.style = 'Table Grid'
    # Шапка
    for i, h in enumerate(headers):
        c = tbl.rows[0].cells[i]
        c.text = ''
        p = c.paragraphs[0]
        p.alignment = WD_ALIGN_PARAGRAPH.CENTER
        r = p.add_run(h)
        r.font.name = 'Times New Roman'
        r.font.size = Pt(font_size)
        r.font.bold = True
        c.vertical_alignment = WD_ALIGN_VERTICAL.CENTER
    # Повтор шапки при переносе
    trPr = tbl.rows[0]._tr.get_or_add_trPr()
    tblHeader = OxmlElement('w:tblHeader')
    trPr.append(tblHeader)

    # Данные
    for ri, row_data in enumerate(rows, start=1):
        for ci, val in enumerate(row_data):
            c = tbl.rows[ri].cells[ci]
            c.text = ''
            p = c.paragraphs[0]
            p.alignment = WD_ALIGN_PARAGRAPH.LEFT
            r = p.add_run(str(val))
            r.font.name = 'Times New Roman'
            r.font.size = Pt(font_size)
    if col_widths_cm:
        for ri in range(len(tbl.rows)):
            for ci, w in enumerate(col_widths_cm):
                tbl.rows[ri].cells[ci].width = Cm(w)
    return tbl

