fig_no = 0; tbl_no = 0

def _f(run, size=14, bold=False, italic=False):
    run.font.name = FONT; run.font.size = Pt(size); run.bold = bold; run.italic = italic
    run._element.rPr.rFonts.set(qn("w:eastAsia"), FONT)

def heading(text):
    p = doc.add_paragraph(); p.paragraph_format.space_before = Pt(12)
    p.paragraph_format.space_after = Pt(6); p.paragraph_format.keep_with_next = True
    _f(p.add_run(text), 14, bold=True); return p

def body(text, first_indent=True):
    p = doc.add_paragraph(); p.alignment = WD_ALIGN_PARAGRAPH.JUSTIFY
    if first_indent: p.paragraph_format.first_line_indent = Cm(1.25)
    _f(p.add_run(text), 14); return p

def figure(fname, caption, width_cm=USABLE_CM):
    global fig_no; fig_no += 1
    path = os.path.join(DIA, fname)
    w, h = Image.open(path).size
    disp_w = width_cm
    if (h / w) * width_cm > 20: disp_w = 20 * w / h
    p = doc.add_paragraph(); p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    p.paragraph_format.space_before = Pt(6); p.paragraph_format.keep_together = True
    p.add_run().add_picture(path, width=Cm(disp_w))
    cap = doc.add_paragraph(); cap.alignment = WD_ALIGN_PARAGRAPH.CENTER
    cap.paragraph_format.space_after = Pt(10)
    _f(cap.add_run(f"Рисунок {fig_no} – {caption}"), 13)
    return fig_no

def table_caption(title):
    global tbl_no; tbl_no += 1
    p = doc.add_paragraph(); p.alignment = WD_ALIGN_PARAGRAPH.RIGHT; p.paragraph_format.space_before = Pt(8)
    _f(p.add_run(f"Таблица {tbl_no}"), 14)
    p2 = doc.add_paragraph(); p2.alignment = WD_ALIGN_PARAGRAPH.CENTER; p2.paragraph_format.space_after = Pt(2)
    _f(p2.add_run(title), 14); return tbl_no

def _shade(cell, hexc):
    tcPr = cell._tc.get_or_add_tcPr(); sh = OxmlElement("w:shd")
    sh.set(qn("w:val"), "clear"); sh.set(qn("w:color"), "auto"); sh.set(qn("w:fill"), hexc); tcPr.append(sh)

def _ct(cell, text, bold=False, size=13, align=None):
    cell.text = ""; p = cell.paragraphs[0]
    if align: p.alignment = align
    p.paragraph_format.line_spacing = 1.0; p.paragraph_format.space_after = Pt(0)
    _f(p.add_run(text), size, bold=bold)

def kv_table(rows, col0_cm=4.2):
    t = doc.add_table(rows=len(rows), cols=2); t.style = "Table Grid"; t.alignment = WD_TABLE_ALIGNMENT.CENTER
    for i,(k,v) in enumerate(rows):
        _ct(t.rows[i].cells[0], k, bold=True); _ct(t.rows[i].cells[1], v)
        t.rows[i].cells[0].width = Cm(col0_cm); t.rows[i].cells[1].width = Cm(USABLE_CM-col0_cm)
        _shade(t.rows[i].cells[0], "EFEFEF")
    doc.add_paragraph().paragraph_format.space_after = Pt(2); return t

def grid_table(headers, rows, widths=None):
    t = doc.add_table(rows=1+len(rows), cols=len(headers)); t.style = "Table Grid"; t.alignment = WD_TABLE_ALIGNMENT.CENTER
    for j,h in enumerate(headers):
        _ct(t.rows[0].cells[j], h, bold=True, align=WD_ALIGN_PARAGRAPH.CENTER); _shade(t.rows[0].cells[j], "D9D9D9")
    for i,row in enumerate(rows, start=1):
        for j,val in enumerate(row): _ct(t.rows[i].cells[j], val)
    if widths:
        for i in range(len(rows)+1):
            for j,wd in enumerate(widths): t.rows[i].cells[j].width = Cm(wd)
    doc.add_paragraph().paragraph_format.space_after = Pt(2); return t

def op_table(name, oblig, links, notes, exc, out, pre, post):
    table_caption(f"Описание системной операции «{name.split('(')[0]}»")
    kv_table([("Имя", name), ("Обязанности", oblig), ("Тип", "Системная"), ("Ссылки", links),
              ("Примечания", notes), ("Исключения", exc), ("Вывод", out),
              ("Предусловие", pre), ("Постусловие", post)], col0_cm=3.8)

