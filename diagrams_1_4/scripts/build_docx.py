def _set_font(run, size=14, bold=False, italic=False, color=None):
    run.font.name = FONT; run.font.size = Pt(size); run.bold = bold; run.italic = italic
    run._element.rPr.rFonts.set(qn("w:eastAsia"), FONT)
    if color: run.font.color.rgb = color

def heading(text, level=2):
    p = doc.add_paragraph()
    p.paragraph_format.space_before = Pt(12); p.paragraph_format.space_after = Pt(6)
    p.paragraph_format.keep_with_next = True
    r = p.add_run(text); _set_font(r, 14, bold=True)
    return p

def body(text, justify=True, first_indent=True):
    p = doc.add_paragraph()
    if justify: p.alignment = WD_ALIGN_PARAGRAPH.JUSTIFY
    if first_indent: p.paragraph_format.first_line_indent = Cm(1.25)
    r = p.add_run(text); _set_font(r, 14)
    return p

def bullet(text):
    p = doc.add_paragraph()
    p.alignment = WD_ALIGN_PARAGRAPH.JUSTIFY
    p.paragraph_format.left_indent = Cm(1.25)
    p.paragraph_format.first_line_indent = Cm(-0.5)
    r = p.add_run("– " + text); _set_font(r, 14)
    return p

def figure(fname, caption, width_cm=USABLE_CM):
    global fig_no
    fig_no += 1
    path = f"{DIA}/{fname}"
    w, h = Image.open(path).size
    # ограничим высоту ~ 20 см
    disp_w = width_cm
    if (h / w) * width_cm > 20:
        disp_w = 20 * w / h
    p = doc.add_paragraph(); p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    p.paragraph_format.space_before = Pt(6)
    r = p.add_run(); r.add_picture(path, width=Cm(disp_w))
    cap = doc.add_paragraph(); cap.alignment = WD_ALIGN_PARAGRAPH.CENTER
    cap.paragraph_format.space_after = Pt(10)
    rr = cap.add_run(f"Рисунок {fig_no} – {caption}"); _set_font(rr, 13)
    return fig_no

def table_caption(title):
    global tbl_no
    tbl_no += 1
    p = doc.add_paragraph(); p.alignment = WD_ALIGN_PARAGRAPH.RIGHT
    p.paragraph_format.space_before = Pt(8)
    r = p.add_run(f"Таблица {tbl_no}"); _set_font(r, 14)
    p2 = doc.add_paragraph(); p2.alignment = WD_ALIGN_PARAGRAPH.CENTER
    p2.paragraph_format.space_after = Pt(2)
    r2 = p2.add_run(title); _set_font(r2, 14)
    return tbl_no

def _shade(cell, hexcolor):
    tcPr = cell._tc.get_or_add_tcPr()
    sh = OxmlElement("w:shd"); sh.set(qn("w:val"), "clear")
    sh.set(qn("w:color"), "auto"); sh.set(qn("w:fill"), hexcolor)
    tcPr.append(sh)

def _cell_text(cell, text, bold=False, size=13, align=None):
    cell.text = ""
    p = cell.paragraphs[0]
    if align: p.alignment = align
    p.paragraph_format.line_spacing = 1.0
    p.paragraph_format.space_after = Pt(0)
    r = p.add_run(text); _set_font(r, size, bold=bold)

def kv_table(rows, col0_cm=4.5):
    """Таблица «поле | значение»."""
    t = doc.add_table(rows=len(rows), cols=2); t.style = "Table Grid"
    t.alignment = WD_TABLE_ALIGNMENT.CENTER
    for i,(k,v) in enumerate(rows):
        _cell_text(t.rows[i].cells[0], k, bold=True)
        _cell_text(t.rows[i].cells[1], v)
        t.rows[i].cells[0].width = Cm(col0_cm)
        t.rows[i].cells[1].width = Cm(USABLE_CM-col0_cm)
        _shade(t.rows[i].cells[0], "EFEFEF")
    doc.add_paragraph().paragraph_format.space_after = Pt(2)
    return t

def grid_table(headers, rows, widths=None, head_fill="D9E2F3"):
    t = doc.add_table(rows=1+len(rows), cols=len(headers)); t.style = "Table Grid"
    t.alignment = WD_TABLE_ALIGNMENT.CENTER
    for j,h in enumerate(headers):
        _cell_text(t.rows[0].cells[j], h, bold=True, align=WD_ALIGN_PARAGRAPH.CENTER)
        _shade(t.rows[0].cells[j], head_fill)
    for i,row in enumerate(rows, start=1):
        for j,val in enumerate(row):
            _cell_text(t.rows[i].cells[j], val)
    if widths:
        for i in range(len(rows)+1):
            for j,wd in enumerate(widths):
                t.rows[i].cells[j].width = Cm(wd)
    doc.add_paragraph().paragraph_format.space_after = Pt(2)
    return t

