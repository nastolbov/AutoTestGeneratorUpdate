def _f(run, size=14, bold=False):
    run.font.name = FONT; run.font.size = Pt(size); run.bold = bold
    run._element.rPr.rFonts.set(qn("w:eastAsia"), FONT)


def h(text, size=14):
    p = doc.add_paragraph(); p.paragraph_format.space_before = Pt(12)
    p.paragraph_format.space_after = Pt(6); p.paragraph_format.keep_with_next = True
    _f(p.add_run(text), size, bold=True); return p


def body(text, indent=True):
    p = doc.add_paragraph(); p.alignment = WD_ALIGN_PARAGRAPH.JUSTIFY
    if indent: p.paragraph_format.first_line_indent = Cm(1.25)
    _f(p.add_run(text), 14); return p


def bullets(items):
    for it in items:
        p = doc.add_paragraph(); p.alignment = WD_ALIGN_PARAGRAPH.JUSTIFY
        p.paragraph_format.left_indent = Cm(1.25); p.paragraph_format.first_line_indent = Cm(-0.5)
        _f(p.add_run("– " + it), 14)


def _shade(cell, hexc):
    tcPr = cell._tc.get_or_add_tcPr(); sh = OxmlElement("w:shd")
    sh.set(qn("w:val"), "clear"); sh.set(qn("w:color"), "auto"); sh.set(qn("w:fill"), hexc); tcPr.append(sh)


def _ct(cell, text, bold=False, size=12, align=WD_ALIGN_PARAGRAPH.LEFT):
    cell.text = ""; p = cell.paragraphs[0]; p.alignment = align
    p.paragraph_format.line_spacing = 1.0; p.paragraph_format.space_after = Pt(0)
    _f(p.add_run(text), size, bold=bold)


def table_caption(title):
    global tbl_no; tbl_no += 1
    p = doc.add_paragraph(); p.alignment = WD_ALIGN_PARAGRAPH.RIGHT; p.paragraph_format.space_before = Pt(8)
    _f(p.add_run(f"Таблица {tbl_no}"), 14)
    p2 = doc.add_paragraph(); p2.alignment = WD_ALIGN_PARAGRAPH.CENTER; p2.paragraph_format.space_after = Pt(2)
    _f(p2.add_run(title), 14); return tbl_no


def test_table(rows):
    headers = ["Дата", "Тестирование\nпроводил", "Описание теста", "Ожидаемый результат", "Результат\nтестирования"]
    widths = [1.9, 2.4, 5.4, 4.1, 2.7]
    t = doc.add_table(rows=1 + len(rows), cols=5); t.style = "Table Grid"; t.alignment = WD_TABLE_ALIGNMENT.CENTER
    for j, hh in enumerate(headers):
        _ct(t.rows[0].cells[j], hh, bold=True, align=WD_ALIGN_PARAGRAPH.CENTER); _shade(t.rows[0].cells[j], "D9D9D9")
    for i, row in enumerate(rows, start=1):
        for j, v in enumerate(row):
            _ct(t.rows[i].cells[j], v)
    for i in range(len(rows) + 1):
        for j, wd in enumerate(widths):
            t.rows[i].cells[j].width = Cm(wd)
    doc.add_paragraph().paragraph_format.space_after = Pt(2)


