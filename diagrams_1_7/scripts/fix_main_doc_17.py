def bullet_set(p, new_text):
    p.runs[1].text = "\t" + new_text
    for r in p.runs[2:]:
        r.text = ""


def fix_bullet(i, needle, new_text):
    if needle in ps[i].text:
        bullet_set(ps[i], new_text)
        return f"P{i}: исправлено"
    return f"P{i}: пропуск (уже исправлено)"


def run_replace(p, old, new):
    for r in p.runs:
        if old in r.text:
            r.text = r.text.replace(old, new)
            return True
    return False


