"""Доработка 2: переписать функциональные (§3.1) и надёжностные (§3.2) требования
ТЗ (Приложение 1) в Столбов_ВКР.docx СТРОГО по факту кода. Главное — убрать
устаревшую концепцию «трёх уровней тестов SMOKE/BASIC/FULL» (в коде выбор уровня
удалён, всегда FULL: TestConfig.java:14, MainController.java:323-324) и
скорректировать формулировки надёжности под реальное поведение (БД: единая
транзакция без явного rollback; ChromeDriver — автозагрузка). Перед каждой
правкой проверяется текущий текст абзаца (assert)."""
import os
from docx import Document

DOC = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "Столбов_ВКР.docx")
d = Document(DOC)
ps = d.paragraphs
n0_par, n0_tbl = len(ps), len(d.tables)


def rewrite_bullet(p, new_text):
    """Маркированный пункт «•»+таб: run[0]='•' сохраняется, текст — во второй run."""
    assert len(p.runs) >= 2 and p.runs[0].text.strip() == "•", f"не маркированный пункт: {p.text[:60]}"
    p.runs[1].text = "\t" + new_text
    for r in p.runs[2:]:
        r.text = ""


def expect(i, needle):
    got = ps[i].text
    assert needle in got, f"P{i}: ожидали «{needle}», получили «{got[:90]}»"


# --- §3.1 Функциональные требования ---
expect(1513, "Maven-проекта")
rewrite_bullet(ps[1513],
    "генерация Maven-проекта автотестов: pom.xml, общие классы (SharedDriver, BaseTest, "
    "TestData), Page Object и тестовый класс на JUnit 5 для каждой тестируемой сущности "
    "(основной PRIMARY и дочерней CHILD), а также CSV-отчёт о классификации сущностей;")

expect(1514, "уровн")  # текущий текст содержит «уровень/уровням» — заменяем целиком
rewrite_bullet(ps[1514],
    "генерация для каждой тестируемой сущности полного набора UI-проверок: наличие полей "
    "формы, валидация обязательных полей (полная и частичная), создание, изменение и "
    "удаление записи (CRUD), логическое удаление и архивирование (при наличии "
    "соответствующих операций), параметрический поиск и проверка гридов;")

expect(1515, "запуск сгенерированных тестов через")
rewrite_bullet(ps[1515],
    "запуск сгенерированных тестов через mvn test, с возможностью выбора подмножества "
    "тестов (по сущностям и видам проверок) и быстрого (headless) режима выполнения;")

# --- §3.2 Требования к надёжности ---
expect(1525, "транзакции")
rewrite_bullet(ps[1525],
    "сохранение результатов прогона в локальную базу данных выполняется в рамках одной "
    "транзакции: записи фиксируются (commit) только при успешном завершении, иначе "
    "незафиксированные данные не сохраняются;")

expect(1526, "degradation")
rewrite_bullet(ps[1526],
    "при сбое записи в базу данных программа должна продолжить работу без сохранения "
    "истории прогона (graceful degradation), а возникшая ошибка — протоколироваться;")

expect(1527, "Maven")
rewrite_bullet(ps[1527],
    "при отсутствии установленного Apache Maven прогон тестов не запускается и выводится "
    "сообщение об ошибке; драйвер браузера (ChromeDriver) загружается автоматически;")

d.save(DOC)

# --- проверка целостности и результата ---
d2 = Document(DOC)
p2 = d2.paragraphs
assert len(p2) == n0_par, f"число абзацев изменилось: {len(p2)} != {n0_par}"
assert len(d2.tables) == n0_tbl, f"число таблиц изменилось: {len(d2.tables)} != {n0_tbl}"
# в §3.1/§3.2 не должно остаться «SMOKE/BASIC/FULL» и «уровн»
bad = []
for i in range(1509, 1530):
    t = p2[i].text
    if any(k in t for k in ("SMOKE", "BASIC", "FULL", "уровн")):
        bad.append((i, t[:70]))
print("OK. абзацев:", len(p2), "таблиц:", len(d2.tables))
print("Остаточные упоминания уровней в §3.1/§3.2:", bad if bad else "нет")
for i in (1513, 1514, 1515, 1525, 1526, 1527):
    print(f"  P{i}: {p2[i].text.strip()}")
